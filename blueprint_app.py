from google import genai
import streamlit as st
import json

# Initialize the Gemini Client
client = genai.Client()

st.set_page_config(layout="wide")
st.title("🗺️ Interactive System Architecture Architect")
st.caption("Convert system descriptions into interactive blueprints with beginner-friendly explanations.")

col1, col2 = st.columns([1, 1.5])

with col1:
    st.subheader("✍️ Describe Your Infrastructure")
    
    default_prompt = (
        "A secure user authentication flow: The user submits a web form to an "
        "API Gateway. The Gateway forwards the request to an Auth Service. The "
        "Auth Service validates credentials against a PostgreSQL Database and "
        "dispatches a success event to a RabbitMQ message broker, which triggers "
        "a Welcome Email Service."
    )
    
    user_description = st.text_area(
        "Type what your system architecture does:",
        value=default_prompt,
        height=220
    )
    
    generate_blueprint = st.button("🚀 Render Architecture Diagram", type="primary")

with col2:
    st.subheader("🎨 Live Architectural Topology")
    
    # Reset or generate new architecture data
    if generate_blueprint or "architecture_data" not in st.session_state:
        if "architecture_data" not in st.session_state or generate_blueprint:
            with st.spinner("Gemini is mapping out the system and drafting student guides..."):
                
                system_prompt = f"""
                You are a computer science professor helping a beginner student understand cloud architecture.
                Analyze the user description below and generate a JSON response containing two main fields:
                1. 'mermaid_code': The raw Mermaid string starting directly with 'graph LR' or 'graph TD'. No markdown accents.
                2. 'glossary': A dictionary mapping every technical component node id/name to a very short, non-technical, simple analogy or description explaining what its job is.

                User Description:
                {user_description}

                Example JSON Shape:
                {{
                  "mermaid_code": "graph LR\\nUser-->Gateway[API Gateway]",
                  "glossary": {{
                    "API Gateway": "The front door security guard. It takes incoming requests from users and passes them to the correct internal server."
                  }}
                }}
                """
                
                interaction = client.interactions.create(
                    model="gemini-3.8-flash",
                    input=system_prompt,
                    response_format={
                        "type": "text",
                        "mime_type": "application/json"
                    }
                )
                
                # Parse and save the compound object into session state
                st.session_state["architecture_data"] = json.loads(interaction.output_text)

    # Render data if safely loaded
    if "architecture_data" in st.session_state:
        app_data = st.session_state["architecture_data"]
        mermaid_code = app_data.get("mermaid_code", "").strip().replace("```mermaid", "").replace("```", "")
        glossary = app_data.get("glossary", {})
        
        try:
            # 1. Render the actual flowchart
            st.mermaid_chart(mermaid_code)
            
            # 2. Render the interactive, beginner-friendly dictionary tool underneath!
            st.write("### 📚 Jargon Buster (Interactive Glossary)")
            st.markdown("Pick any item from the architecture map below to learn exactly what its job is in plain English:")
            
            # Create a selection box populated with the tech words generated by Gemini
            selected_component = st.selectbox(
                "Select a component to inspect:", 
                options=list(glossary.keys())
            )
            
            if selected_component:
                st.success(f"**What `{selected_component}` does:** {glossary[selected_component]}")
                
        except Exception as e:
            st.error("Failed to parse visual components. Click 'Render Architecture Diagram' to retry.")
